import { readdir, readFile, stat, writeFile, mkdir } from "node:fs/promises";
import { dirname, extname, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { STORY_PHOTO_LABELS } from "../src/media/photo-library.js";

const extensions = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const natural = new Intl.Collator("en", { numeric: true, sensitivity: "variant" });

async function imageFiles(directory) {
  let entries;
  try { entries = await readdir(directory, { withFileTypes: true }); }
  catch (error) { if (error.code === "ENOENT") return []; throw error; }
  const files = [];
  for (const entry of entries.sort((a, b) => natural.compare(a.name, b.name) || a.name.localeCompare(b.name, "en"))) {
    if (entry.name.startsWith(".")) continue;
    const filename = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await imageFiles(filename));
    else if (entry.isFile() && extensions.has(extname(entry.name).toLowerCase())) files.push(filename);
  }
  return files;
}

export async function collectPhotoManifest(publicDir) {
  const url = filename => "/" + relative(publicDir, filename).split(sep).map(encodeURIComponent).join("/");
  const orbit = (await imageFiles(resolve(publicDir, "photos/orbit"))).map(url);
  const story = {};
  for (const filename of await imageFiles(resolve(publicDir, "photos/story"))) {
    const key = filename.slice(filename.lastIndexOf(sep) + 1, -extname(filename).length);
    if (!(key in STORY_PHOTO_LABELS)) continue;
    if (story[key]) throw new Error(`Dua file memakai slot ${key}: pilih satu file di public/photos/story/.`);
    story[key] = url(filename);
  }
  return { story, orbit };
}

export async function validateMedia(content, publicDir) {
  if (!content.recipient || !content.sender) throw new Error("Isi recipient dan sender di src/content.js.");
  if (content.birthday && Number.isNaN(Date.parse(content.birthday))) throw new Error("Tanggal birthday tidak valid.");
  if (!content.poems?.length || !content.letter?.length) throw new Error("Puisi dan surat tidak boleh kosong.");
  for (const key of content.letterPhotos)
    if (!(key in content.photos)) throw new Error(`Slot foto surat tidak dikenal: ${key}`);
  if (!content.tracks?.[0]?.src) throw new Error("Sumber musik latar belum diisi.");
  const sources = new Set([...Object.values(content.photos).filter(Boolean), content.tracks[0].src]);
  for (const source of sources) {
    if (/^https?:/i.test(source)) continue;
    if (/^(blob:|data:)/i.test(source)) throw new Error(`Media permanen harus berupa file di public/: ${source.slice(0, 45)}`);
    const pathname = decodeURIComponent(new URL(source, "https://gift.invalid/").pathname);
    const filename = resolve(publicDir, "." + pathname);
    const inside = relative(publicDir, filename);
    if (inside === ".." || inside.startsWith(".." + sep)) throw new Error(`Path keluar dari public/: ${source}`);
    let info;
    try { info = await stat(filename); }
    catch { throw new Error(`File media tidak ditemukan: public${pathname}. Periksa src/content.js.`); }
    if (!info.isFile() || !info.size) throw new Error(`File media kosong atau bukan file: public${pathname}`);
  }
  return sources.size;
}

export async function prepareMedia(root) {
  const publicDir = resolve(root, "public");
  const manifest = await collectPhotoManifest(publicDir);
  const target = resolve(root, "src/generated/photo-manifest.js");
  const source = "// Generated by npm run prepare:media. Edit src/content.js, not this file.\n"
    + "export const photoManifest = " + JSON.stringify(manifest, null, 2) + ";\n";
  await mkdir(dirname(target), { recursive: true });
  const previous = await readFile(target, "utf8").catch(() => "");
  if (source !== previous) await writeFile(target, source);
  // Import after generation, so a build never reads yesterday's file list.
  const { content } = await import(pathToFileURL(resolve(root, "src/content.js")).href);
  const count = await validateMedia(content, publicDir);
  console.log(`Media siap: ${Object.values(content.photos).filter(Boolean).length} slot foto terisi; ${count} file/sumber unik termasuk musik.`);
  return manifest;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  try { await prepareMedia(root); }
  catch (error) { console.error(`\nKonten belum siap: ${error.message}\n`); process.exitCode = 1; }
}
